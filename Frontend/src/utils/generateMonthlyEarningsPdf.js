import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export function generateMonthlyEarningsPdf(packageRows, month) {
  const doc = new jsPDF({ orientation: "landscape" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;
  const totals = packageRows.reduce(
    (sum, row) => ({
      confirmed: sum.confirmed + Number(row.confirmed || 0),
      unconfirmed: sum.unconfirmed + Number(row.unconfirmed || 0),
      refund: sum.refund + Number(row.refund || 0),
      total: sum.total + Number(row.total || 0),
    }),
    { confirmed: 0, unconfirmed: 0, refund: 0, total: 0 },
  );

  doc.setFillColor(41, 171, 135);
  doc.rect(0, 0, pageWidth, 32, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Monthly Earnings Report", margin, 15);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`Month: ${formatMonthLabel(month)}`, margin, 23);
  doc.text(`Generated on: ${new Date().toLocaleDateString()}`, pageWidth - margin, 23, {
    align: "right",
  });

  autoTable(doc, {
    startY: 40,
    head: [["Package", "Confirmed Earnings", "Unconfirmed Earnings", "Refund", "Total"]],
    body: packageRows.length
      ? packageRows.map((row) => [
          row.packageName,
          `$ ${Number(row.confirmed || 0).toLocaleString()}`,
          `$ ${Number(row.unconfirmed || 0).toLocaleString()}`,
          `$ ${Number(row.refund || 0).toLocaleString()}`,
          `$ ${Number(row.total || 0).toLocaleString()}`,
        ])
      : [["No bookings for this month.", "", "", "", ""]],
    foot: [[
      "Total",
      `$ ${totals.confirmed.toLocaleString()}`,
      `$ ${totals.unconfirmed.toLocaleString()}`,
      `$ ${totals.refund.toLocaleString()}`,
      `$ ${totals.total.toLocaleString()}`,
    ]],
    theme: "grid",
    headStyles: { fillColor: [41, 171, 135], textColor: 255, fontSize: 9, fontStyle: "bold" },
    footStyles: { fillColor: [214, 235, 224], textColor: 30, fontSize: 9, fontStyle: "bold" },
    bodyStyles: { fontSize: 9, textColor: 50 },
    alternateRowStyles: { fillColor: [240, 250, 245] },
    columnStyles: {
      1: { halign: "right" },
      2: { halign: "right" },
      3: { halign: "right" },
      4: { halign: "right" },
    },
    didParseCell: (data) => {
      if (data.section === "foot" && data.column.index === 0) {
        data.cell.styles.halign = "right";
      }
    },
    margin: { left: margin, right: margin },
  });

  addPageNumbers(doc, pageWidth);
  doc.save(`Monthly_Earnings_Report_${month}.pdf`);
}

function formatMonthLabel(month) {
  const [year, monthNumber] = String(month).split("-");
  return new Date(Number(year), Number(monthNumber) - 1, 1).toLocaleDateString("en-US", {
    month: "long",
    year: "numeric",
  });
}

function addPageNumbers(doc, pageWidth) {
  const pageCount = doc.internal.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFontSize(9);
    doc.setTextColor(150);
    doc.text(`Page ${page} of ${pageCount} — Generated by RapidX`, pageWidth / 2, 200, {
      align: "center",
    });
  }
}
