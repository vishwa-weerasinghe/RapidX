import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

/**
 * Generates the Annual Booking Report PDF from /appointments/annual-report data.
 *
 * @param {object} report - { year, rows: [{ month, label, total_confirmed,
 *                          total_in_cart, total_pending, total_cancelled,
 *                          earnings_confirmed }], totals: { ... } }
 */
export function generateAnnualReportPdf(report) {
  const doc = new jsPDF({ orientation: "landscape" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;
  const green = [41, 171, 135];

  // ---------- Header band ----------
  doc.setFillColor(green[0], green[1], green[2]);
  doc.rect(0, 0, pageWidth, 32, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Annual Booking Report", margin, 15);
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text(`Year: ${report.year}`, margin, 23);
  doc.text(
    `Generated on: ${new Date().toLocaleDateString()}`,
    pageWidth - margin,
    23,
    { align: "right" }
  );

  // ---------- Yearly overview cards ----------
  const cards = [
    { label: "Confirmed Bookings", value: report.totals.total_confirmed, highlight: false },
    { label: "In Cart Bookings", value: report.totals.total_in_cart, highlight: false },
    { label: "Pending Bookings", value: report.totals.total_pending, highlight: false },
    { label: "Cancelled Bookings", value: report.totals.total_cancelled, highlight: false },
    { label: "Earnings (Confirmed)", value: `$ ${Number(report.totals.earnings_confirmed).toLocaleString()}`, highlight: true },
  ];

  let y = 44;
  const cardW = (pageWidth - margin * 2) / cards.length;

  cards.forEach((card, i) => {
    const x = margin + i * cardW;

    if (card.highlight) {
      doc.setFillColor(green[0], green[1], green[2]);
      doc.setTextColor(255, 255, 255);
    } else {
      doc.setFillColor(245, 245, 245);
      doc.setTextColor(50, 50, 50);
    }

    doc.roundedRect(x, y, cardW - 4, 22, 2, 2, "F");

    doc.setFontSize(8);
    doc.setFont("helvetica", "bold");
    doc.text(card.label.toUpperCase(), x + 4, y + 8);

    doc.setFontSize(13);
    doc.text(String(card.value), x + 4, y + 17);

    doc.setFont("helvetica", "normal");
  });

  // ---------- Monthly table ----------
  autoTable(doc, {
    startY: y + 32,
    head: [[
      "Month",
      "Total Confirmed Bookings",
      "Total In Cart Bookings",
      "Total Pending Bookings",
      "Total Cancelled Bookings",
      "Earnings from Confirmed Bookings",
    ]],
    body: report.rows.map((r) => [
      r.label,
      r.total_confirmed,
      r.total_in_cart,
      r.total_pending,
      r.total_cancelled,
      `$ ${Number(r.earnings_confirmed).toLocaleString()}`,
    ]),
    foot: [[
      "Entire Year",
      report.totals.total_confirmed,
      report.totals.total_in_cart,
      report.totals.total_pending,
      report.totals.total_cancelled,
      `$ ${Number(report.totals.earnings_confirmed).toLocaleString()}`,
    ]],
    theme: "grid",
    headStyles: {
      fillColor: green,
      textColor: 255,
      fontSize: 9,
      fontStyle: "bold",
    },
    footStyles: {
      fillColor: [214, 235, 224],
      textColor: 30,
      fontSize: 9,
      fontStyle: "bold",
    },
    bodyStyles: { fontSize: 9, textColor: 50 },
    alternateRowStyles: { fillColor: [240, 250, 245] },
    columnStyles: {
      1: { halign: "center" },
      2: { halign: "center" },
      3: { halign: "center" },
      4: { halign: "center" },
      5: { halign: "right" },
    },
    margin: { left: margin, right: margin },
  });

  // ---------- Footer with page numbers ----------
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(9);
    doc.setTextColor(150);
    doc.text(
      `Page ${i} of ${pageCount} — Generated by RapidX`,
      pageWidth / 2,
      200,
      { align: "center" }
    );
  }

  doc.save(`Annual_Booking_Report_${report.year}.pdf`);
}
