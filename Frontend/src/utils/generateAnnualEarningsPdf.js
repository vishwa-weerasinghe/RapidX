import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export function generateAnnualEarningsPdf(report) {
  const doc = new jsPDF({ orientation: "landscape" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;
  const totals = report.totals;
  const calculateTotal = (item) =>
    Number(item.earnings_confirmed || 0) - Number(item.refunds || 0);

  doc.setFillColor(41, 171, 135);
  doc.rect(0, 0, pageWidth, 32, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Annual Earnings Report", margin, 15);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`Year: ${report.year}`, margin, 23);
  doc.text(`Generated on: ${new Date().toLocaleDateString()}`, pageWidth - margin, 23, {
    align: "right",
  });

  autoTable(doc, {
    startY: 40,
    head: [["Month", "Confirmed Earnings", "Unconfirmed Earnings", "Refund", "Total"]],
    body: report.rows.map((row) => [
      row.label,
      `$ ${Number(row.earnings_confirmed || 0).toLocaleString()}`,
      `$ ${Number(row.earnings_unconfirmed || 0).toLocaleString()}`,
      `$ ${Number(row.refunds || 0).toLocaleString()}`,
      `$ ${calculateTotal(row).toLocaleString()}`,
    ]),
    foot: [[
      `Entire Year (${report.year})`,
      `$ ${Number(totals.earnings_confirmed || 0).toLocaleString()}`,
      `$ ${Number(totals.earnings_unconfirmed || 0).toLocaleString()}`,
      `$ ${Number(totals.refunds || 0).toLocaleString()}`,
      `$ ${calculateTotal(totals).toLocaleString()}`,
    ]],
    theme: "grid",
    headStyles: { fillColor: [41, 171, 135], textColor: 255, fontSize: 9, fontStyle: "bold" },
    footStyles: { fillColor: [214, 235, 224], textColor: 30, fontSize: 9, fontStyle: "bold" },
    bodyStyles: { fontSize: 9, textColor: 50 },
    alternateRowStyles: { fillColor: [240, 250, 245] },
    columnStyles: {
      1: { halign: "right" },
      2: { halign: "right" },
      3: { halign: "right" },
      4: { halign: "right" },
    },
    didParseCell: (data) => {
      if (data.section === "foot" && data.column.index === 0) {
        data.cell.styles.halign = "right";
      }
    },
    margin: { left: margin, right: margin },
  });

  const pageCount = doc.internal.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFontSize(9);
    doc.setTextColor(150);
    doc.text(`Page ${page} of ${pageCount} — Generated by RapidX`, pageWidth / 2, 200, {
      align: "center",
    });
  }

  doc.save(`Annual_Earnings_Report_${report.year}.pdf`);
}
